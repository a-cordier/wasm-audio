#!/usr/bin/env node
// Turn a preset from an EXPORT file into a factory preset source file.
//
//   node scripts/factory-preset.mjs <export.json> <preset name | current> <slug>
//
// Writes src/core/factory-presets/<slug>.ts and prints the FACTORY_SOURCES
// line to add (or keep) in src/core/preset-storage.ts. "current" takes the
// live workspace the file was exported from, unsaved edits included.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [file, pick, slug] = process.argv.slice(2);
if (!file || !pick || !/^[a-z0-9-]+$/.test(slug ?? "")) {
  console.error("usage: node scripts/factory-preset.mjs <export.json> <preset name | current> <slug>");
  process.exit(1);
}

const bundle = JSON.parse(readFileSync(file, "utf8"));
if (bundle.format !== "wasm-audio.presets") {
  console.error(`not a preset export (format: ${bundle.format})`);
  process.exit(1);
}

const wanted = pick.trim().toUpperCase();
const entry =
  wanted === "CURRENT" ? bundle.current : (bundle.presets ?? []).find((p) => p.name === wanted);
if (!entry?.session) {
  const names = (bundle.presets ?? []).map((p) => p.name).join(", ") || "(none)";
  console.error(`preset "${pick}" not found. In the file: ${names}; current: ${bundle.current?.name ?? "(none)"}`);
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const license = readFileSync(join(root, "lca-header.txt"), "utf8").trimEnd().split("\n");
const header = ["/*", ...license.map((l) => (l ? ` * ${l}` : " *")), " */"].join("\n");
const constName = `${slug.toUpperCase().replace(/-/g, "_")}_SESSION`;
const { ui: _ui, preset: _preset, ...session } = entry.session;
const out = join(root, "src/core/factory-presets", `${slug}.ts`);
writeFileSync(
  out,
  `${header}\n\n/** Factory preset session (generated by scripts/factory-preset.mjs from an\n * app export). Stored in the RackSession shape and sanitized on load like\n * any saved preset. */\nexport const ${constName}: unknown = ${JSON.stringify(session, null, 2)};\n`
);
console.log(`wrote ${out} (${session.slots.length} devices, ${session.transport?.bpm ?? "?"} BPM)`);
console.log(`FACTORY_SOURCES entry: { id: "factory-${slug}", name: "${entry.name}", session: ${constName} },`);
